def _parse_csv_list(value: str | None, cast_type: Any = str) -> list[Any]:
    if value is None or value == "":
        return []
    items = [item for item in value.split(",") if item != ""]
    if cast_type is str:
        return items
    if cast_type is int:
        # Metadata may encode integers with decimal formatting (e.g., "1.000").
        return [int(round(float(item))) for item in items]
    return [cast_type(item) for item in items]


def _load_onnx_metadata(path: str) -> dict[str, str]:
    model = onnx.load(path)
    return {entry.key: entry.value for entry in model.metadata_props}


def _infer_reference_length_from_policy(path: str) -> int | None:
    """Infer reference motion length encoded in exported ONNX policy."""
    model = onnx.load(path)
    graph = model.graph
    input_names = {inp.name for inp in graph.input}
    if "time_step" not in input_names:
        return None

    producer_by_output: dict[str, onnx.NodeProto] = {}
    for node in graph.node:
        for out_name in node.output:
            producer_by_output[out_name] = node

    scalar_constants: dict[str, float] = {}
    for init in graph.initializer:
        arr = np.asarray(numpy_helper.to_array(init))
        if arr.size == 1:
            scalar_constants[init.name] = float(arr.reshape(()))

    for node in graph.node:
        if node.op_type != "Constant":
            continue
        if len(node.output) != 1:
            continue
        for attr in node.attribute:
            if attr.name != "value" or not attr.HasField("t"):
                continue
            arr = np.asarray(numpy_helper.to_array(attr.t))
            if arr.size == 1:
                scalar_constants[node.output[0]] = float(arr.reshape(()))

    depends_cache: dict[str, bool] = {}

    def _depends_on_time_step(tensor_name: str) -> bool:
        if tensor_name == "time_step":
            return True
        if tensor_name in depends_cache:
            return depends_cache[tensor_name]

        producer = producer_by_output.get(tensor_name)
        if producer is None:
            depends_cache[tensor_name] = False
            return False

        depends = any(
            _depends_on_time_step(inp_name) for inp_name in producer.input if inp_name != ""
        )
        depends_cache[tensor_name] = depends
        return depends

    candidates: list[int] = []

    def _append_candidate(value: float):
        rounded = int(round(value))
        if abs(value - rounded) > 1e-5 or rounded < 0:
            return
        # Exported policy clamps `time_step` to `time_step_total - 1`.
        candidates.append(rounded + 1)

    for node in graph.node:
        if node.op_type == "Clip":
            if len(node.input) < 3:
                continue
            x_name, _, max_name = node.input[:3]
            if x_name and _depends_on_time_step(x_name) and max_name in scalar_constants:
                _append_candidate(scalar_constants[max_name])
            continue

        if node.op_type == "Min":
            if len(node.input) != 2:
                continue
            a_name, b_name = node.input
            a_depends = a_name != "" and _depends_on_time_step(a_name)
            b_depends = b_name != "" and _depends_on_time_step(b_name)
            if a_depends == b_depends:
                continue
            const_name = b_name if a_depends else a_name
            if const_name in scalar_constants:
                _append_candidate(scalar_constants[const_name])

    if not candidates:
        return None
    return max(candidates)


def quat_conjugate_wxyz(q: np.ndarray) -> np.ndarray:
    out = q.copy()
    out[..., 1:] *= -1.0
    return out


def quat_normalize_wxyz(q: np.ndarray) -> np.ndarray:
    norm = np.linalg.norm(q, axis=-1, keepdims=True)
    norm = np.maximum(norm, 1e-8)
    return q / norm


def quat_mul_wxyz(q1: np.ndarray, q2: np.ndarray) -> np.ndarray:
    w1, x1, y1, z1 = np.moveaxis(q1, -1, 0)
    w2, x2, y2, z2 = np.moveaxis(q2, -1, 0)
    w = w1 * w2 - x1 * x2 - y1 * y2 - z1 * z2
    x = w1 * x2 + x1 * w2 + y1 * z2 - z1 * y2
    y = w1 * y2 - x1 * z2 + y1 * w2 + z1 * x2
    z = w1 * z2 + x1 * y2 - y1 * x2 + z1 * w2
    return np.stack([w, x, y, z], axis=-1)


def quat_rotate_wxyz(q: np.ndarray, v: np.ndarray) -> np.ndarray:
    q_xyz = q[..., 1:]
    q_w = q[..., :1]
    t = 2.0 * np.cross(q_xyz, v)
    return v + q_w * t + np.cross(q_xyz, t)


def quat_rotate_inverse_wxyz(q: np.ndarray, v: np.ndarray) -> np.ndarray:
    return quat_rotate_wxyz(quat_conjugate_wxyz(q), v)


def quat_to_matrix_wxyz(q: np.ndarray) -> np.ndarray:
    qn = quat_normalize_wxyz(q)
    w, x, y, z = np.moveaxis(qn, -1, 0)

    ww = w * w
    xx = x * x
    yy = y * y
    zz = z * z
    wx = w * x
    wy = w * y
    wz = w * z
    xy = x * y
    xz = x * z
    yz = y * z

    m00 = ww + xx - yy - zz
    m01 = 2.0 * (xy - wz)
    m02 = 2.0 * (xz + wy)

    m10 = 2.0 * (xy + wz)
    m11 = ww - xx + yy - zz
    m12 = 2.0 * (yz - wx)

    m20 = 2.0 * (xz - wy)
    m21 = 2.0 * (yz + wx)
    m22 = ww - xx - yy + zz

    return np.stack(
        [
            np.stack([m00, m01, m02], axis=-1),
            np.stack([m10, m11, m12], axis=-1),
            np.stack([m20, m21, m22], axis=-1),
        ],
        axis=-2,
    )


def quat_error_magnitude_wxyz(q_ref: np.ndarray, q_cur: np.ndarray) -> np.ndarray:
    q_ref_n = quat_normalize_wxyz(q_ref)
    q_cur_n = quat_normalize_wxyz(q_cur)
    dot = np.sum(q_ref_n * q_cur_n, axis=-1)
    dot = np.clip(np.abs(dot), -1.0, 1.0)
    return 2.0 * np.arccos(dot)


def yaw_quat_wxyz(q: np.ndarray) -> np.ndarray:
    w, x, y, z = q
    yaw = np.arctan2(2.0 * (w * z + x * y), 1.0 - 2.0 * (y * y + z * z))
    return np.array([np.cos(yaw * 0.5), 0.0, 0.0, np.sin(yaw * 0.5)], dtype=np.float32)


